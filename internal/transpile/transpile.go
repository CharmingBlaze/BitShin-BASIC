func sanitizeIdent(name string) string {
	key := lex.IdentKey(name)
	key = strings.ReplaceAll(key, ".", "_")
	var b strings.Builder
	for _, r := range key {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	s := b.String()
	if s == "type" || s == "var" || s == "func" || s == "range" || s == "map" || s == "chan" || s == "select" || s == "case" || s == "default" {
		s = "v_" + s
	}
	return "v_" + s
}

func quoteFields(fields []string) string {
	parts := make([]string, len(fields))
	for i, f := range fields {
		parts[i] = strconv.Quote(strings.ToLower(strings.TrimRight(f, "$#%")))
	}
	return strings.Join(parts, ", ")
}

func sanitizeFn(name string) string {
	key := lex.IdentKey(name)
	key = strings.ReplaceAll(key, ".", "_")
	return "fn_" + key
}

func (w *writer) sym(name string) string {
	id := sanitizeIdent(name)
	if w.inFunc && w.locals[id] {
		return "loc_" + id
	}
	return id
}

// emitName reads a variable. Inside a function, a bare assignment shadows a
// global only after that assignment has run.
func (w *writer) emitName(name string) string {
	id := sanitizeIdent(name)
	sym := w.sym(name)
	if w.inFunc && w.shadow[id] {
		return fmt.Sprintf("_bb_shadow(&%s_on, %s, %s)", sym, sym, id)
	}
	return sym
}

func (w *writer) shadowOn(name string) string {
	id := sanitizeIdent(name)
	if w.inFunc && w.shadow[id] {
		return w.sym(name) + "_on = true"
	}
	return ""
}

func (w *writer) markDefined(name string) {
	if w.checkStrict && !w.inFunc {
		w.line(fmt.Sprintf("_bb_defined[%q] = true", lex.IdentKey(name)))
	}
}

// emitGuardedAssign rejects a bare assignment under Strict when the name was
// not introduced. Inside a function that includes a global that was not named
// with Global.
func (w *writer) emitGuardedAssign(name, store string) {
	if !w.checkStrict || (w.inFunc && w.declared[sanitizeIdent(name)]) {
		w.line(store)
		w.markDefined(name)
		return
	}
	key := lex.IdentKey(name)
	cond := "_bb_strict"
	if !w.inFunc {
		cond = fmt.Sprintf("_bb_strict && !_bb_defined[%q]", key)
	}
	w.line(fmt.Sprintf("if %s {", cond))
	w.indent++
	w.line(fmt.Sprintf("_bb_undef(%q)", key))
	w.indent--
	w.line("} else {")
	w.indent++
	w.line(store)
	w.markDefined(name)
	w.indent--
	w.line("}")
}

func programHasStrict(stmts []ast.Stmt) bool {
	var walk func([]ast.Stmt) bool
	walk = func(list []ast.Stmt) bool {
		for _, s := range list {
			switch n := s.(type) {
			case *ast.StrictStmt:
				return true
			case *ast.FuncDecl:
				if walk(n.Body) {
					return true
				}
			case *ast.TypeDecl:
				for _, m := range n.Methods {
					if m != nil && walk(m.Body) {
						return true
					}
				}
			case *ast.MethodDecl:
				if walk(n.Body) {
					return true
				}
			case *ast.NamespaceDecl:
				if walk(n.Stmts) {
					return true
				}
			case *ast.IfStmt:
				if walk(n.Then) || walk(n.Else) {
					return true
				}
				for _, el := range n.ElseIf {
					if walk(el.Body) {
						return true
					}
				}
			case *ast.WhileStmt:
				if walk(n.Body) {
					return true
				}
			case *ast.ForStmt:
				if walk(n.Body) {
					return true
				}
			case *ast.RepeatStmt:
				if walk(n.Body) {
					return true
				}
			case *ast.SelectStmt:
				for _, c := range n.Cases {
					if walk(c.Body) {
						return true
					}
				}
				if walk(n.Default) {
					return true
				}
			case *ast.TryStmt:
				if walk(n.Body) || walk(n.Catch) {
					return true
				}
			}
		}
		return false
	}
	return walk(stmts)
}

func declaredFuncNames(fn *ast.FuncDecl) map[string]bool {
	declared := map[string]bool{}
	if fn == nil {
		return declared
	}
	for _, p := range fn.Params {
		declared[sanitizeIdent(p)] = true
	}
	explicit := map[string]bool{}
	collectExplicitGlobals(fn.Body, explicit)
	for id := range explicit {
		declared[id] = true
	}
	var walk func([]ast.Stmt)
	walk = func(stmts []ast.Stmt) {
		for _, s := range stmts {
			switch n := s.(type) {
			case *ast.LocalStmt:
				for _, name := range n.Names {
					declared[sanitizeIdent(name)] = true
				}
			case *ast.ConstStmt:
				for _, name := range n.Names {
					declared[sanitizeIdent(name)] = true
				}
			case *ast.DimStmt:
				declared[sanitizeIdent(n.Name)] = true
			case *ast.ForStmt:
				declared[sanitizeIdent(n.Var)] = true
				walk(n.Body)
			case *ast.IfStmt:
				walk(n.Then)
				for _, el := range n.ElseIf {
					walk(el.Body)
				}
				walk(n.Else)
			case *ast.WhileStmt:
				walk(n.Body)
			case *ast.RepeatStmt:
				walk(n.Body)
			case *ast.SelectStmt:
				for _, c := range n.Cases {
					walk(c.Body)
				}
				walk(n.Default)
			case *ast.TryStmt:
				walk(n.Body)
				walk(n.Catch)
			}
		}
	}
	walk(fn.Body)
	return declared
}

func isConstIdent(name string) bool {
	k := lex.IdentKey(name)
	switch k {
	case "true", "false", "yes", "no", "null", "pi":
		return true
	}
	if _, ok := syntax.KeyConstants[k]; ok {
		return true
	}
	if _, ok := syntax.WeatherConstants[k]; ok {
		return true
	}
	if _, ok := syntax.NetConstants[k]; ok {
		return true
	}
	if _, ok := syntax.PhysicsConstants[k]; ok {
		return true
	}
	return false
}

func collectDataExprs(stmts []ast.Stmt) []ast.Expr {
	var out []ast.Expr
	var walk func([]ast.Stmt)
	walk = func(list []ast.Stmt) {
		for _, s := range list {
			switch t := s.(type) {
			case *ast.DataStmt:
				out = append(out, t.Values...)
			case *ast.IfStmt:
				walk(t.Then)
				for _, e := range t.ElseIf {
					walk(e.Body)
				}
				walk(t.Else)
			case *ast.WhileStmt:
				walk(t.Body)
			case *ast.ForStmt:
				walk(t.Body)
			case *ast.RepeatStmt:
				walk(t.Body)
			case *ast.SelectStmt:
				for _, c := range t.Cases {
					walk(c.Body)
				}
				walk(t.Default)
			case *ast.FuncDecl:
				walk(t.Body)
			}
		}
	}
	walk(stmts)
	return out
}

func collectProgram(stmts []ast.Stmt) (
	typeDecls []*ast.TypeDecl,
	funcs []*ast.FuncDecl,
	methods []*ast.FuncDecl,
	top []ast.Stmt,
	data []ast.Expr,
	namespaces map[string]bool,
) {
	namespaces = map[string]bool{}
	var walk func([]ast.Stmt, string)
	walk = func(list []ast.Stmt, prefix string) {
		qual := func(name string) string {
			if prefix == "" {
				return name
			}
			return prefix + "." + name
		}
		for _, s := range list {
			switch t := s.(type) {
			case *ast.TypeDecl:
				td := *t
				td.Name = qual(t.Name)
				typeDecls = append(typeDecls, &td)
				for _, m := range t.Methods {
					if m == nil {
						continue
					}
					md := *m
					md.Name = td.Name + "." + m.Name
					md.Params = append([]string{"Self"}, m.Params...)
					funcs = append(funcs, &md)
					methods = append(methods, &md)
				}
			case *ast.MethodDecl:
				md := &ast.FuncDecl{
					Src: t.Src, Name: qual(t.Recv) + "." + t.Name,
					Params: append([]string{"Self"}, t.Params...), Defaults: t.Defaults, Body: t.Body,
				}
				funcs = append(funcs, md)
				methods = append(methods, md)
			case *ast.FuncDecl:
				fn := *t
				fn.Name = qual(t.Name)
				funcs = append(funcs, &fn)
			case *ast.NamespaceDecl:
				namespaces[lex.IdentKey(qual(t.Name))] = true
				walk(t.Stmts, qual(t.Name))
			case *ast.DataStmt:
				data = append(data, t.Values...)
			default:
				if prefix == "" {
					top = append(top, s)
				}
			}
		}
	}
	walk(stmts, "")
	return typeDecls, funcs, methods, top, data, namespaces
}

func emitMethodTable(w *writer, methods, funcs []*ast.FuncDecl) {
	for _, m := range methods {
		w.line(fmt.Sprintf("_bb_methods[%q] = func(w *runtime.World, self value.Value, args []value.Value) value.Value {", lex.IdentKey(m.Name)))
		w.indent++
		w.line(fmt.Sprintf("return %s(w, append([]value.Value{self}, args...)...)", sanitizeFn(m.Name)))
		w.indent--
		w.line("}")
	}
	for _, fn := range funcs {
		if len(fn.Params) != 0 {
			continue
		}
		if strings.Contains(fn.Name, ".") && strings.HasSuffix(strings.ToLower(fn.Name), ".self") {
			continue
		}
		// Zero-arg functions can be state-machine callbacks (AddState name string).
		isMethod := false
		for _, m := range methods {
			if m == fn {
				isMethod = true
				break
			}
		}
		if isMethod {
			continue
		}
		w.line(fmt.Sprintf("_bb_callbacks[%q] = %s", lex.IdentKey(fn.Name), sanitizeFn(fn.Name)))
	}
}

func collectVars(stmt ast.Stmt, vars map[string]bool) {
	if stmt == nil {
		return
	}
	switch s := stmt.(type) {
	case *ast.AssignStmt:
		if s.Name != "" {
			vars[sanitizeIdent(s.Name)] = true
		}
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
		}
	case *ast.LocalStmt:
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
		}
	case *ast.GlobalStmt:
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
		}
	case *ast.DimStmt:
		vars[sanitizeIdent(s.Name)] = true
	case *ast.ForStmt:
		vars[sanitizeIdent(s.Var)] = true
		for _, b := range s.Body {
			collectVars(b, vars)
		}
	case *ast.IfStmt:
		for _, b := range s.Then {
			collectVars(b, vars)
		}
		for _, el := range s.ElseIf {
			for _, b := range el.Body {
				collectVars(b, vars)
			}
		}
		for _, b := range s.Else {
			collectVars(b, vars)
		}
	case *ast.WhileStmt:
		for _, b := range s.Body {
			collectVars(b, vars)
		}
	case *ast.RepeatStmt:
		for _, b := range s.Body {
			collectVars(b, vars)
		}
	case *ast.SelectStmt:
		for _, c := range s.Cases {
			for _, b := range c.Body {
				collectVars(b, vars)
			}
		}
		for _, b := range s.Default {
			collectVars(b, vars)
		}
	case *ast.ReadStmt:
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
		}
	case *ast.ConstStmt:
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
		}
	case *ast.EnumStmt:
		for _, name := range s.Names {
			vars[sanitizeIdent(name)] = true
			if s.Name != "" {
				vars[sanitizeIdent(s.Name+"_"+name)] = true
			}
		}
		if s.Name != "" {
			vars[sanitizeIdent(s.Name)] = true
		}
	case *ast.TryStmt:
		if s.ErrVar != "" {
			vars[sanitizeIdent(s.ErrVar)] = true
		}
		for _, b := range s.Body {
			collectVars(b, vars)
		}
		for _, b := range s.Catch {
			collectVars(b, vars)
		}
	}
}

func collectExplicitGlobals(stmts []ast.Stmt, g map[string]bool) {
	for _, s := range stmts {
		switch n := s.(type) {
		case *ast.GlobalStmt:
			for _, name := range n.Names {
				g[sanitizeIdent(name)] = true
			}
		case *ast.EnumStmt:
			for _, name := range n.Names {
				g[sanitizeIdent(name)] = true
				if n.Name != "" {
					g[sanitizeIdent(n.Name+"_"+name)] = true
				}
			}
			if n.Name != "" {
				g[sanitizeIdent(n.Name)] = true
			}
		case *ast.FuncDecl:
			collectExplicitGlobals(n.Body, g)
		case *ast.IfStmt:
			collectExplicitGlobals(n.Then, g)
			for _, el := range n.ElseIf {
				collectExplicitGlobals(el.Body, g)
			}
			collectExplicitGlobals(n.Else, g)
		case *ast.WhileStmt:
			collectExplicitGlobals(n.Body, g)
		case *ast.ForStmt:
			collectExplicitGlobals(n.Body, g)
		case *ast.RepeatStmt:
			collectExplicitGlobals(n.Body, g)
		case *ast.SelectStmt:
			for _, c := range n.Cases {
				collectExplicitGlobals(c.Body, g)
			}
			collectExplicitGlobals(n.Default, g)
		case *ast.TryStmt:
			collectExplicitGlobals(n.Body, g)
			collectExplicitGlobals(n.Catch, g)
		}
	}
}

func collectFuncLocals(fn *ast.FuncDecl) map[string]bool {
	locals := map[string]bool{}
	explicit := map[string]bool{}
	collectExplicitGlobals(fn.Body, explicit)
	for _, p := range fn.Params {
		locals[sanitizeIdent(p)] = true
	}
	var walk func([]ast.Stmt)
	walk = func(stmts []ast.Stmt) {
		for _, s := range stmts {
			switch n := s.(type) {
			case *ast.LocalStmt:
				for _, name := range n.Names {
					locals[sanitizeIdent(name)] = true
				}
			case *ast.ConstStmt:
				for _, name := range n.Names {
					locals[sanitizeIdent(name)] = true
				}
			case *ast.ForStmt:
				locals[sanitizeIdent(n.Var)] = true
				walk(n.Body)
			case *ast.DimStmt:
				locals[sanitizeIdent(n.Name)] = true
			case *ast.AssignStmt:
				if len(n.Index) > 0 || len(n.Fields) > 0 {
					break
				}
				names := n.Names
				if len(names) == 0 {
					names = []string{n.Name}
				}
				for _, name := range names {
					id := sanitizeIdent(name)
					if !explicit[id] {
						locals[id] = true
					}
				}
			case *ast.ReadStmt:
				for i, name := range n.Names {
					if i < len(n.Quals) && len(n.Quals[i]) > 0 {
						continue
					}
					id := sanitizeIdent(name)
					if !explicit[id] {
						locals[id] = true
					}
				}
			case *ast.TryStmt:
				if n.ErrVar != "" {
					locals[sanitizeIdent(n.ErrVar)] = true
				}
				walk(n.Body)
				walk(n.Catch)
			case *ast.IfStmt:
				walk(n.Then)
				for _, el := range n.ElseIf {
					walk(el.Body)
				}
				walk(n.Else)
			case *ast.WhileStmt:
				walk(n.Body)
			case *ast.RepeatStmt:
				walk(n.Body)
			case *ast.SelectStmt:
				for _, c := range n.Cases {
					walk(c.Body)
				}
				walk(n.Default)
			}
		}
	}
	walk(fn.Body)
	return locals
}

func noteGlobals(stmts []ast.Stmt, locals, globals map[string]bool) {
	var walkExpr func(ast.Expr)
	var walkStmts func([]ast.Stmt)
	walkExpr = func(e ast.Expr) {
		if e == nil {
			return
		}
		switch n := e.(type) {
		case *ast.IdentExpr:
			if isConstIdent(n.Name) {
				return
			}
			id := sanitizeIdent(n.Name)
			if !locals[id] {
				globals[id] = true
			}
		case *ast.IndexExpr:
			if !isConstIdent(n.Name) {
				id := sanitizeIdent(n.Name)
				if !locals[id] {
					globals[id] = true
				}
			}
			for _, a := range n.Index {
				walkExpr(a)
			}
		case *ast.UnaryExpr:
			walkExpr(n.X)
		case *ast.FmtExpr:
			walkExpr(n.X)
		case *ast.BinaryExpr:
			walkExpr(n.Left)
			walkExpr(n.Right)
		case *ast.FieldExpr:
			walkExpr(n.X)
		case *ast.MethodExpr:
			walkExpr(n.X)
			for _, a := range n.Args {
				walkExpr(a)
			}
		case *ast.CallExpr:
			for _, a := range n.Args {
				walkExpr(a)
			}
		case *ast.VecExpr:
			for _, a := range n.Elems {
				walkExpr(a)
			}
		case *ast.NewExpr:
			for _, a := range n.Args {
				walkExpr(a)
			}
		}
	}
	walkStmts = func(list []ast.Stmt) {
		for _, s := range list {
			switch n := s.(type) {
			case *ast.AssignStmt:
				walkExpr(n.Value)
				for _, a := range n.Index {
					walkExpr(a)
				}
			case *ast.LocalStmt, *ast.GlobalStmt, *ast.ConstStmt:
				var values []ast.Expr
				switch t := s.(type) {
				case *ast.LocalStmt:
					values = t.Values
				case *ast.GlobalStmt:
					values = t.Values
				case *ast.ConstStmt:
					values = t.Values
				}
				for _, v := range values {
					walkExpr(v)
				}
			case *ast.DimStmt:
				for _, sz := range n.Sizes {
					walkExpr(sz)
				}
			case *ast.CallStmt:
				for _, a := range n.Args {
					walkExpr(a)
				}
			case *ast.MethodStmt:
				if !isConstIdent(n.Object) {
					id := sanitizeIdent(n.Object)
					if !locals[id] {
						globals[id] = true
					}
				}
				for _, idx := range n.Index {
					walkExpr(idx)
				}
				for _, a := range n.Args {
					walkExpr(a)
				}
			case *ast.ExprStmt:
				walkExpr(n.Value)
			case *ast.IfStmt:
				walkExpr(n.Cond)
				walkStmts(n.Then)
				for _, el := range n.ElseIf {
					walkExpr(el.Cond)
					walkStmts(el.Body)
				}
				walkStmts(n.Else)
			case *ast.WhileStmt:
				walkExpr(n.Cond)
				walkStmts(n.Body)
			case *ast.ForStmt:
				walkExpr(n.Start)
				walkExpr(n.End)
				walkExpr(n.Step)
				walkExpr(n.In)
				walkStmts(n.Body)
			case *ast.RepeatStmt:
				walkExpr(n.Until)
				walkStmts(n.Body)
			case *ast.SelectStmt:
				walkExpr(n.Value)
				for _, c := range n.Cases {
					for _, it := range c.Items {
						walkExpr(it.Low)
						walkExpr(it.High)
					}
					walkStmts(c.Body)
				}
				walkStmts(n.Default)
			case *ast.TryStmt:
				walkStmts(n.Body)
				walkStmts(n.Catch)
			}
		}
	}
	walkStmts(stmts)
}

func emitFunction(w *writer, fn *ast.FuncDecl, globals map[string]bool) {
	w.inFunc = true
	w.fnName = lex.IdentKey(fn.Name)
	w.retType = fn.Ret
	w.locals = collectFuncLocals(fn)
	defer func() {
		w.inFunc = false
		w.fnName = ""
		w.retType = ""
		w.locals = nil
		w.shadow = nil
		w.declared = nil
	}()

	paramVars := map[string]bool{}
	for _, p := range fn.Params {
		paramVars[sanitizeIdent(p)] = true
	}
	w.declared = declaredFuncNames(fn)
	w.shadow = map[string]bool{}
	for id := range w.locals {
		if paramVars[id] {
			continue
		}
		if globals[id] {
			w.shadow[id] = true
		}
	}
	sig := "w *runtime.World"
	if len(fn.Params) > 0 {
		sig += ", _bb_args ...value.Value"
	}
	w.line(fmt.Sprintf("func %s(%s) value.Value {", sanitizeFn(fn.Name), sig))
	w.indent++

	for i, p := range fn.Params {
		id := sanitizeIdent(p)
		sym := w.sym(p)
		def := "value.Num(0)"
		if i < len(fn.Defaults) && fn.Defaults[i] != nil {
			def = w.emitExpr(fn.Defaults[i], "w")
		}
		w.line(fmt.Sprintf("var %s value.Value", sym))
		w.line(fmt.Sprintf("if len(_bb_args) > %d { %s = _bb_args[%d] } else { %s = %s }", i, sym, i, sym, def))
		if w.intNames[id] {
			w.line(fmt.Sprintf("%s = value.Num(float64(int((%s).Number())))", sym, sym))
		} else if w.strNames[id] {
			w.line(fmt.Sprintf("%s = value.Str((%s).String())", sym, sym))
		}
		if i < len(fn.ParamTypes) && fn.ParamTypes[i] != "" {
			w.line(fmt.Sprintf("if err := _bb_as(%q, &%s); err != nil {", fn.ParamTypes[i], sym))
			w.line("\t_bb_err = err")
			w.line("\tif _bb_try == 0 && !_bb_live { panic(err) }")
			w.line("\tif _bb_try == 0 && _bb_live { fmt.Println(err) }")
			w.line("\treturn value.Num(0)")
			w.line("}")
		}
	}

	names := make([]string, 0, len(w.locals))
	for id := range w.locals {
		if !paramVars[id] {
			names = append(names, "loc_"+id)
		}
	}
	sort.Strings(names)
	for _, name := range names {
		w.line(fmt.Sprintf("var %s value.Value", name))
		if w.shadow[strings.TrimPrefix(name, "loc_")] {
			w.line(fmt.Sprintf("var %s_on bool", name))
		}
	}
	if len(names) > 0 {
		w.line("")
	}

	for _, s := range fn.Body {
		emitStmt(w, s, "w")
	}

	if !terminalReturn(fn.Body) {
		w.line("return value.Num(0)")
	}
	w.indent--
	w.line("}")
}

// terminalReturn reports whether Go would treat a trailing return as unreachable.
func terminalReturn(stmts []ast.Stmt) bool {
	if len(stmts) == 0 {
		return false
	}
	switch s := stmts[len(stmts)-1].(type) {
	case *ast.ReturnStmt:
		return true
	case *ast.ExitStmt:
		return s.Function
	case *ast.IfStmt:
		if len(s.Else) == 0 || !terminalReturn(s.Then) || !terminalReturn(s.Else) {
			return false
		}
		for _, el := range s.ElseIf {
			if !terminalReturn(el.Body) {
				return false
			}
		}
		return true
	default:
		return false
	}
}

func emitStmt(w *writer, stmt ast.Stmt, worldVar string) {
	if stmt == nil {
		return
	}
	switch s := stmt.(type) {
	case *ast.AssignStmt:
		if len(s.Names) > 1 {
			w.line("{")
			w.indent++
			w.line(fmt.Sprintf("_pack := %s", w.emitExpr(s.Value, worldVar)))
			for i, name := range s.Names {
				w.emitGuardedAssign(name, fmt.Sprintf("if %d < len(_pack.Elems) { %s }", i, w.emitStore(name, fmt.Sprintf("_pack.Elems[%d]", i))))
			}
			w.indent--
			w.line("}")
			break
		}
		if len(s.Fields) > 0 && len(s.Index) > 0 {
			keys := make([]string, len(s.Index))
			for i, idx := range s.Index {
				keys[i] = w.emitExpr(idx, worldVar)
			}
			w.line(fmt.Sprintf("if err := _bb_set_at(%s, %s, []string{%s}, %s); err != nil {", w.emitName(s.Name), w.emitExpr(s.Value, worldVar), quoteFields(s.Fields), strings.Join(keys, ", ")))
			w.line("\t_bb_err = err")
			w.line("\tif _bb_try == 0 && !_bb_live { panic(err) }")
			w.line("\tif _bb_try == 0 && _bb_live { fmt.Println(err) }")
			w.line("}")
		} else if len(s.Fields) > 0 {
			w.line(fmt.Sprintf("_bb_set_fields(%s, %s, %s)", w.emitName(s.Name), w.emitExpr(s.Value, worldVar), quoteFields(s.Fields)))
		} else if len(s.Index) > 0 {
			keys := make([]string, len(s.Index))
			for i, idx := range s.Index {
				keys[i] = w.emitExpr(idx, worldVar)
			}
			w.line(fmt.Sprintf("_bb_set_index(%s, %s, %s)", w.emitName(s.Name), w.emitExpr(s.Value, worldVar), strings.Join(keys, ", ")))
		} else {
			w.emitGuardedAssign(s.Name, w.emitStore(s.Name, w.emitExpr(s.Value, worldVar)))
		}

	case *ast.LocalStmt:
		for i, name := range s.Names {
			val := "value.Num(0)"
			if i < len(s.Values) && s.Values[i] != nil {
				val = w.emitExpr(s.Values[i], worldVar)
			}
			if s.Static {
				key := w.fnName + "." + lex.IdentKey(name)
				sym := w.sym(name)
				w.line(fmt.Sprintf("if _bbPrev, _bbOk := _bbStatic[%q]; _bbOk { %s = _bbPrev } else { %s = %s }", key, sym, sym, val))
				w.line(fmt.Sprintf("defer func() { _bbStatic[%q] = %s }()", key, sym))
				continue
			}
			w.line(w.emitStore(name, val))
			w.markDefined(name)
		}

	case *ast.GlobalStmt:
		for i, name := range s.Names {
			if i < len(s.Values) && s.Values[i] != nil {
				w.line(w.emitStore(name, w.emitExpr(s.Values[i], worldVar)))
				w.markDefined(name)
				continue
			}
			// Inside a function, Global name keeps the current value.
			if !w.inFunc {
				w.line(w.emitStore(name, "value.Num(0)"))
			}
			w.markDefined(name)
		}

	case *ast.ConstStmt:
		for i, name := range s.Names {
			val := "value.Num(0)"
			if i < len(s.Values) && s.Values[i] != nil {
				val = w.emitExpr(s.Values[i], worldVar)
			}
			w.line(w.emitStore(name, val))
			w.markDefined(name)
		}

	case *ast.EnumStmt:
		w.line("{")
		w.indent++
		w.line("_enum := 0.0")
		for i, name := range s.Names {
			if i < len(s.Values) && s.Values[i] != nil {
				w.line(fmt.Sprintf("_enum = (%s).Number()", w.emitExpr(s.Values[i], worldVar)))
			}
			w.line(fmt.Sprintf("%s = value.Num(_enum)", w.sym(name)))
			w.markDefined(name)
			if s.Name != "" {
				w.line(fmt.Sprintf("%s = value.Num(_enum)", w.sym(s.Name+"_"+name)))
				w.markDefined(s.Name + "_" + name)
			}
			w.line("_enum++")
		}
		if s.Name != "" {
			w.markDefined(s.Name)
			w.line(fmt.Sprintf("%s = value.Value{Kind: value.KindStruct, TypeName: %q, Fields: map[string]value.Value{", w.sym(s.Name), strings.ToLower(s.Name)))
			w.indent++
			for _, name := range s.Names {
				w.line(fmt.Sprintf("%q: %s,", lex.IdentKey(name), w.sym(name)))
			}
			w.indent--
			w.line("}}")
		}
		w.indent--
		w.line("}")

	case *ast.DimStmt:
		sizes := make([]string, len(s.Sizes))
		for i, sz := range s.Sizes {
			sizes[i] = fmt.Sprintf("int((%s).Number())", w.emitExpr(sz, worldVar))
		}
		sym := w.sym(s.Name)
		if s.Redim {
			w.line("{")
			w.indent++
			w.line(fmt.Sprintf("_old := %s", w.emitName(s.Name)))
			w.line(fmt.Sprintf("%s = value.Array([]int{%s})", sym, strings.Join(sizes, ", ")))
			if on := w.shadowOn(s.Name); on != "" {
				w.line(on)
			}
			w.line(fmt.Sprintf("if _old.Kind == value.KindArray { n := len(_old.Elems); if n > len(%s.Elems) { n = len(%s.Elems) }; copy(%s.Elems, _old.Elems[:n]); if %s.TypeName == \"\" { %s.TypeName = _old.TypeName } }", sym, sym, sym, sym, sym))
			if s.TypeName != "" {
				w.line(fmt.Sprintf("%s.TypeName = %q", sym, strings.ToLower(s.TypeName)))
			}
			w.indent--
			w.line("}")
			w.markDefined(s.Name)
			break
		}
		w.line(fmt.Sprintf("%s = value.Array([]int{%s})", sym, strings.Join(sizes, ", ")))
		if on := w.shadowOn(s.Name); on != "" {
			w.line(on)
		}
		if s.TypeName != "" {
			w.line(fmt.Sprintf("%s.TypeName = %q", sym, strings.ToLower(s.TypeName)))
		}
		w.markDefined(s.Name)

	case *ast.CallStmt:
		exprStr := w.emitCall(s.Name, s.Args, worldVar)
		w.line("_ = " + exprStr)

	case *ast.MethodStmt:
		w.line("_ = " + w.emitMethodStmt(s, worldVar))

	case *ast.DeleteStmt:
		w.line(fmt.Sprintf("_bb_untrack(%s)", w.emitName(s.Name)))
		w.line(w.emitStore(s.Name, "value.Num(0)"))

	case *ast.EraseStmt:
		if s.All {
			w.line("_bb_erase_all()")
			break
		}
		w.line(w.emitStore(s.Name, "value.Num(0)"))

	case *ast.YieldStmt:
		w.line("_bb_yield()")

	case *ast.ExprStmt:
		w.line("_ = " + w.emitExpr(s.Value, worldVar))

	case *ast.IfStmt:
		w.line(fmt.Sprintf("if (%s).IsTrue() {", w.emitExpr(s.Cond, worldVar)))
		w.indent++
		for _, b := range s.Then {
			emitStmt(w, b, worldVar)
		}
		w.indent--
		for _, el := range s.ElseIf {
			w.line(fmt.Sprintf("} else if (%s).IsTrue() {", w.emitExpr(el.Cond, worldVar)))
			w.indent++
			for _, b := range el.Body {
				emitStmt(w, b, worldVar)
			}
			w.indent--
		}
		if len(s.Else) > 0 {
			w.line("} else {")
			w.indent++
			for _, b := range s.Else {
				emitStmt(w, b, worldVar)
			}
			w.indent--
		}
		w.line("}")

	case *ast.WhileStmt:
		kind := "while"
		if s.Tag != "" {
			kind = s.Tag
		}
		label := ""
		if loopNeedsLabel(s.Body, kind) {
			label = w.pushLoop(kind)
			w.line(label + ":")
		}
		w.line(fmt.Sprintf("for %s.Running() && (%s).IsTrue() {", worldVar, w.emitExpr(s.Cond, worldVar)))
		w.indent++
		for _, b := range s.Body {
			emitStmt(w, b, worldVar)
		}
		w.indent--
		w.line("}")
		if label != "" {
			w.popLoop()
		}

	case *ast.ForStmt:
		if s.EachType != "" {
			label := ""
			if loopNeedsLabel(s.Body, "for") {
				label = w.pushLoop("for")
			}
			w.line("{")
			w.indent++
			if label != "" {
				w.line(label + ":")
			}
			w.line(fmt.Sprintf("for _, _bb_it := range append([]value.Value(nil), _bb_liveInst[%q]...) {", strings.ToLower(s.EachType)))
			w.line(fmt.Sprintf("if !%s.Running() { break }", worldVar))
			w.line(w.emitStore(s.Var, "_bb_it"))
			w.indent++
			for _, b := range s.Body {
				emitStmt(w, b, worldVar)
			}
			w.indent--
			w.line("}")
			w.indent--
			w.line("}")
			if label != "" {
				w.popLoop()
			}
			break
		}
		if s.In != nil {
			label := ""
			if loopNeedsLabel(s.Body, "for") {
				label = w.pushLoop("for")
			}
			w.line("{")
			w.indent++
			if label != "" {
				w.line(label + ":")
			}
			w.line(fmt.Sprintf("for _, _bb_it := range _bb_iter(%s) {", w.emitExpr(s.In, worldVar)))
			w.line(fmt.Sprintf("if !%s.Running() { break }", worldVar))
			w.line(w.emitStore(s.Var, "_bb_it"))
			w.indent++
			for _, b := range s.Body {
				emitStmt(w, b, worldVar)
			}
			w.indent--
			w.line("}")
			w.indent--
			w.line("}")
			if label != "" {
				w.popLoop()
			}
			break
		}
		start := w.emitExpr(s.Start, worldVar)
		end := w.emitExpr(s.End, worldVar)
		stepVal := "1.0"
		if s.Step != nil {
			stepVal = fmt.Sprintf("(%s).Number()", w.emitExpr(s.Step, worldVar))
		}
		label := ""
		if loopNeedsLabel(s.Body, "for") {
			label = w.pushLoop("for")
		}
		w.line("{")
		w.indent++
		w.markDefined(s.Var)
		w.line(w.emitStore(s.Var, start))
		w.line(fmt.Sprintf("_step := %s", stepVal))
		w.line(fmt.Sprintf("_end := (%s).Number()", end))
		if label != "" {
			w.line(label + ":")
		}
		w.line("for {")
		w.indent++
		w.line(fmt.Sprintf("if !%s.Running() { break }", worldVar))
		w.line(fmt.Sprintf("_cur := (%s).Number()", w.emitName(s.Var)))
		w.line("if !((_step >= 0 && _cur <= _end) || (_step < 0 && _cur >= _end)) { break }")
		for _, b := range s.Body {
			emitStmt(w, b, worldVar)
		}
		w.line(fmt.Sprintf("_step = %s", stepVal))
		w.line(fmt.Sprintf("_end = (%s).Number()", end))
		w.line(w.emitStore(s.Var, fmt.Sprintf("value.Num((%s).Number()+_step)", w.emitName(s.Var))))
		w.indent--
		w.line("}")
		w.indent--
		w.line("}")
		if label != "" {
			w.popLoop()
		}

	case *ast.RepeatStmt:
		kind := s.Tag
		if kind == "" {
			kind = "repeat"
		}
		label := ""
		if loopNeedsLabel(s.Body, kind) {
			label = w.pushLoop(kind)
			w.line(label + ":")
		}
		w.line(fmt.Sprintf("for %s.Running() {", worldVar))
		w.indent++
		for _, b := range s.Body {
			emitStmt(w, b, worldVar)
		}
		if s.Until != nil {
			w.line(fmt.Sprintf("if (%s).IsTrue() { break }", w.emitExpr(s.Until, worldVar)))
		}
		w.indent--
		w.line("}")
		if label != "" {
			w.popLoop()
		}

	case *ast.SelectStmt:
		valStr := w.emitExpr(s.Value, worldVar)
		w.line("{")
		w.indent++
		w.line(fmt.Sprintf("_sel := %s", valStr))
		w.line("switch {")
		for _, c := range s.Cases {
			conds := make([]string, len(c.Items))
			for i, it := range c.Items {
				if it.High != nil {
					conds[i] = fmt.Sprintf("_bb_case_range(_sel, %s, %s)", w.emitExpr(it.Low, worldVar), w.emitExpr(it.High, worldVar))
				} else {
					conds[i] = fmt.Sprintf("value.Cmp(_sel, %s) == 0", w.emitExpr(it.Low, worldVar))
				}
			}
			w.line(fmt.Sprintf("case %s:", strings.Join(conds, " || ")))
			w.indent++
			for _, b := range c.Body {
				emitStmt(w, b, worldVar)
			}
			w.indent--
		}
		if len(s.Default) > 0 {
			w.line("default:")
			w.indent++
			for _, b := range s.Default {
				emitStmt(w, b, worldVar)
			}
			w.indent--
		}
		w.line("}")
		w.indent--
		w.line("}")

	case *ast.DataStmt:
		// Collected at init time

	case *ast.ReadStmt:
		for i, name := range s.Names {
			if i < len(s.Quals) && len(s.Quals[i]) > 0 {
				w.line(fmt.Sprintf("_bb_set_fields(%s, _bb_read_data(), %s)", w.emitName(name), quoteFields(s.Quals[i])))
			} else {
				w.line(w.emitStore(name, "_bb_read_data()"))
			}
		}

	case *ast.RestoreStmt:
		w.line("_bb_data_pc = 0")

	case *ast.ReturnStmt:
		expr := "value.Num(0)"
		if s.Value != nil {
			expr = w.emitExpr(s.Value, worldVar)
		}
		if w.retType != "" {
			expr = fmt.Sprintf("_bb_coerce(%q, %s)", w.retType, expr)
		}
		w.line("return " + expr)

	case *ast.ExitStmt:
		if s.Function {
			w.line("return value.Num(0)")
			break
		}
		if label := w.loopLabel(s.Loop); label != "" {
			w.line("break " + label)
		}

	case *ast.EndStmt:
		w.line("os.Exit(0)")
	case *ast.StrictStmt:
		if w.checkStrict {
			w.line("_bb_strict = true")
		}
	case *ast.TryStmt:
		w.line("_bb_try++")
		w.line("_bb_err = nil")
		for _, b := range s.Body {
			w.line("if _bb_err == nil {")
			w.indent++
			emitStmt(w, b, worldVar)
			w.indent--
			w.line("}")
		}
		w.line("if _bb_err != nil {")
		w.indent++
		if s.ErrVar != "" {
			w.line(fmt.Sprintf("%s = value.Str(_bb_err.Error())", w.sym(s.ErrVar)))
		}
		w.line("_bb_err = nil")
		for _, b := range s.Catch {
			emitStmt(w, b, worldVar)
		}
		w.indent--
		w.line("}")
		w.line("_bb_try--")
	}
}

// quitOrSides matches the interpreter: after the first Flip, `KeyHit Or frames > 8`
// becomes `frames > 8 And KeyHit` so a startup key does not end the game on frame 9.
func quitOrSides(e *ast.BinaryExpr) (frames, hit ast.Expr, ok bool) {
	if e == nil || !strings.EqualFold(e.Op, "or") {
		return nil, nil, false
	}
	leftHit, leftFrames := isKeyQuery(e.Left), isFramesPastExpr(e.Left)
	rightHit, rightFrames := isKeyQuery(e.Right), isFramesPastExpr(e.Right)
	if leftHit && rightFrames {
		return e.Right, e.Left, true
	}
	if rightHit && leftFrames {
		return e.Left, e.Right, true
	}
	return nil, nil, false
}

func isKeyQuery(e ast.Expr) bool {
	c, ok := e.(*ast.CallExpr)
	if !ok {
		return false
	}
	switch lex.IdentKey(c.Name) {
	case "keyhit", "keydown":
		return true
	}
	return false
}

func hoistAnons(stmts []ast.Stmt) []*ast.FuncDecl {
	var out []*ast.FuncDecl
	seq := 0
	var walkStmts func([]ast.Stmt)
	var walkExpr func(ast.Expr)
	walkExprs := func(list []ast.Expr) {
		for _, e := range list {
			walkExpr(e)
		}
	}
	walkExpr = func(e ast.Expr) {
		if e == nil {
			return
		}
		switch t := e.(type) {
		case *ast.FuncExpr:
			if t.Decl == nil {
				return
			}
			seq++
			if t.Decl.Name == "" {
				t.Decl.Name = fmt.Sprintf("__anon%d", seq)
			}
			out = append(out, t.Decl)
			walkStmts(t.Decl.Body)
		case *ast.BinaryExpr:
			walkExpr(t.Left)
			walkExpr(t.Right)
		case *ast.UnaryExpr:
			walkExpr(t.X)
		case *ast.CallExpr:
			walkExprs(t.Args)
		case *ast.MethodExpr:
			walkExpr(t.X)
			walkExprs(t.Args)
		case *ast.FieldExpr:
			walkExpr(t.X)
		case *ast.IndexExpr:
			walkExprs(t.Index)
		case *ast.VecExpr:
			walkExprs(t.Elems)
		case *ast.FmtExpr:
			walkExpr(t.X)
		case *ast.NewExpr:
			walkExprs(t.Args)
		}
	}
	walkStmts = func(list []ast.Stmt) {
		for _, s := range list {
			switch t := s.(type) {
			case *ast.AssignStmt:
				walkExprs(t.Index)
				walkExpr(t.Value)
			case *ast.CallStmt:
				walkExprs(t.Args)
			case *ast.MethodStmt:
				walkExprs(t.Index)
				walkExprs(t.Args)
			case *ast.ExprStmt:
				walkExpr(t.Value)
			case *ast.IfStmt:
				walkExpr(t.Cond)
				walkStmts(t.Then)
				for _, el := range t.ElseIf {
					walkExpr(el.Cond)
					walkStmts(el.Body)
				}
				walkStmts(t.Else)
			case *ast.WhileStmt:
				walkExpr(t.Cond)
				walkStmts(t.Body)
			case *ast.ForStmt:
				walkExpr(t.Start)
				walkExpr(t.End)
				walkExpr(t.Step)
				walkExpr(t.In)
				walkStmts(t.Body)
			case *ast.RepeatStmt:
				walkExpr(t.Until)
				walkStmts(t.Body)
			case *ast.ReturnStmt:
				walkExpr(t.Value)
			case *ast.LocalStmt:
				walkExprs(t.Values)
			case *ast.GlobalStmt:
				walkExprs(t.Values)
			case *ast.ConstStmt:
				walkExprs(t.Values)
			case *ast.DimStmt:
				walkExprs(t.Sizes)
			case *ast.FuncDecl:
				walkStmts(t.Body)
			case *ast.TypeDecl:
				for _, m := range t.Methods {
					if m != nil {
						walkStmts(m.Body)
					}
				}
			case *ast.MethodDecl:
				walkStmts(t.Body)
			case *ast.NamespaceDecl:
				walkStmts(t.Stmts)
			case *ast.SelectStmt:
				walkExpr(t.Value)
				for _, c := range t.Cases {
					for _, it := range c.Items {
						walkExpr(it.Low)
						walkExpr(it.High)
					}
					walkStmts(c.Body)
				}
				walkStmts(t.Default)
			case *ast.TryStmt:
				walkStmts(t.Body)
				walkStmts(t.Catch)
			case *ast.DataStmt:
				walkExprs(t.Values)
			}
		}
	}
	walkStmts(stmts)
	return out
}

func isFramesPastExpr(e ast.Expr) bool {
	b, ok := e.(*ast.BinaryExpr)
	if !ok || (b.Op != ">" && b.Op != ">=") {
		return false
	}
	id, ok := b.Left.(*ast.IdentExpr)
	if !ok || !strings.EqualFold(id.Name, "frames") {
		return false
	}
	n, ok := b.Right.(*ast.NumberExpr)
	return ok && n.Value <= 60
}

func (w *writer) emitExpr(expr ast.Expr, worldVar string) string {
	if expr == nil {
		return "value.Num(0)"
	}
	switch e := expr.(type) {
	case *ast.NumberExpr:
		return fmt.Sprintf("value.Num(%s)", strconv.FormatFloat(e.Value, 'f', -1, 64))

	case *ast.StringExpr:
		return fmt.Sprintf("value.Str(%q)", e.Value)

	case *ast.IdentExpr:
		k := lex.IdentKey(e.Name)
		switch k {
		case "true", "yes":
			return "value.Num(1)"
		case "false", "no", "null":
			return "value.Num(0)"
		case "pi":
			return "value.Num(math.Pi)"
		default:
			if n, ok := syntax.KeyConstants[k]; ok {
				return fmt.Sprintf("value.Num(%s)", strconv.FormatFloat(n, 'f', -1, 64))
			}
			if s, ok := syntax.WeatherConstants[k]; ok {
				return fmt.Sprintf("value.Str(%q)", s)
			}
			if n, ok := syntax.NetConstants[k]; ok {
				return fmt.Sprintf("value.Num(%d)", int(n))
			}
			if n, ok := syntax.PhysicsConstants[k]; ok {
				return fmt.Sprintf("value.Num(%s)", strconv.FormatFloat(n, 'f', -1, 64))
			}
			return w.emitName(e.Name)
		}

	case *ast.IndexExpr:
		keys := make([]string, len(e.Index))
		for i, idx := range e.Index {
			keys[i] = w.emitExpr(idx, worldVar)
		}
		if len(keys) == 0 {
			return fmt.Sprintf("_bb_index(%s)", w.emitName(e.Name))
		}
		return fmt.Sprintf("_bb_index(%s, %s)", w.emitName(e.Name), strings.Join(keys, ", "))

	case *ast.FieldExpr:
		return fmt.Sprintf("func() value.Value { if f, ok := (%s).Field(%q); ok { return f }; return value.Num(0) }()",
			w.emitExpr(e.X, worldVar), e.Field)

	case *ast.NewExpr:
		if td, ok := w.types[lex.IdentKey(e.Type)]; ok {
			return w.emitConstruct(td, e.Args, worldVar)
		}
		return fmt.Sprintf("_bb_track(_bb_new_struct(%q))", strings.ToLower(e.Type))

	case *ast.FuncRefExpr:
		return fmt.Sprintf("value.Func(%q)", e.Name)

	case *ast.FuncExpr:
		if e.Decl == nil || e.Decl.Name == "" {
			return "value.Num(0)"
		}
		return fmt.Sprintf("value.Func(%q)", e.Decl.Name)

	case *ast.MethodExpr:
		return w.emitDot(e.X, e.Name, e.Args, worldVar)

	case *ast.VecExpr:
		elems := make([]string, len(e.Elems))
		for i, el := range e.Elems {
			elems[i] = w.emitExpr(el, worldVar)
		}
		return fmt.Sprintf("value.Vec([]value.Value{%s})", strings.Join(elems, ", "))

	case *ast.BinaryExpr:
		left := w.emitExpr(e.Left, worldVar)
		right := w.emitExpr(e.Right, worldVar)
		switch strings.ToLower(e.Op) {
		case "+":
			return fmt.Sprintf("value.Add(%s, %s)", left, right)
		case "-":
			return fmt.Sprintf("_bb_sub(%s, %s)", left, right)
		case "*":
			return fmt.Sprintf("_bb_mul(%s, %s)", left, right)
		case "/":
			return fmt.Sprintf("_bb_div(%s, %s)", left, right)
		case "^":
			return fmt.Sprintf("value.Num(math.Pow((%s).Number(), (%s).Number()))", left, right)
		case "mod":
			return fmt.Sprintf("_bb_mod(%s, %s)", left, right)
		case "=":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) == 0)", left, right)
		case "<>":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) != 0)", left, right)
		case "<":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) < 0)", left, right)
		case "<=":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) <= 0)", left, right)
		case ">":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) > 0)", left, right)
		case ">=":
			return fmt.Sprintf("_bb_bool(value.Cmp(%s, %s) >= 0)", left, right)
		case "and":
			return fmt.Sprintf("_bb_and(func() value.Value { return %s }, func() value.Value { return %s })", left, right)
		case "or":
			if frames, hit, ok := quitOrSides(e); ok {
				return fmt.Sprintf("func() value.Value { if _bb_live { return _bb_and(func() value.Value { return %s }, func() value.Value { return %s }) }; return _bb_or(func() value.Value { return %s }, func() value.Value { return %s }) }()",
					w.emitExpr(frames, worldVar), w.emitExpr(hit, worldVar), left, right)
			}
			return fmt.Sprintf("_bb_or(func() value.Value { return %s }, func() value.Value { return %s })", left, right)
		case "xor":
			return fmt.Sprintf("_bb_xor(%s, %s)", left, right)
		case "shl":
			return fmt.Sprintf("value.Num(float64(int64((%s).Number()) << uint64((%s).Number())))", left, right)
		case "shr":
			return fmt.Sprintf("value.Num(float64(int64((%s).Number()) >> uint64((%s).Number())))", left, right)
		default:
			return fmt.Sprintf("value.Num(0)")
		}

	case *ast.FmtExpr:
		return fmt.Sprintf("value.Str(_bb_fmt(%s, %q))", w.emitExpr(e.X, worldVar), e.Spec)

	case *ast.UnaryExpr:
		x := w.emitExpr(e.X, worldVar)
		switch strings.ToLower(e.Op) {
		case "-":
			return fmt.Sprintf("value.Num(-(%s).Number())", x)
		case "+":
			return x
		case "not":
			return fmt.Sprintf("_bb_bool(!(%s).IsTrue())", x)
		default:
			return x
		}

	case *ast.CallExpr:
		return w.emitCall(e.Name, e.Args, worldVar)

	default:
		return "value.Num(0)"
	}
}

func (w *writer) emitCall(name string, args []ast.Expr, worldVar string) string {
	// EcsVersion$ / EcsName$ are the same commands as EcsVersion / EcsName.
	lower := lex.IdentKey(name)

	// Builtin standard library functions
	switch lower {
	case "print":
		argStrs := make([]string, len(args))
		for i, a := range args {
			argStrs[i] = w.emitExpr(a, worldVar)
		}
		if len(argStrs) == 0 {
			return fmt.Sprintf("_bb_print(%s)", worldVar)
		}
		return fmt.Sprintf("_bb_print(%s, %s)", worldVar, strings.Join(argStrs, ", "))

	case "sin":
		return fmt.Sprintf("value.Num(math.Sin(_bb_deg((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "cos":
		return fmt.Sprintf("value.Num(math.Cos(_bb_deg((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "tan":
		return fmt.Sprintf("value.Num(math.Tan(_bb_deg((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "asin":
		return fmt.Sprintf("value.Num(_bb_rad(math.Asin((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "acos":
		return fmt.Sprintf("value.Num(_bb_rad(math.Acos((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "atan":
		return fmt.Sprintf("value.Num(_bb_rad(math.Atan((%s).Number())))", w.emitExprArg(args, 0, worldVar))
	case "atan2":
		return fmt.Sprintf("value.Num(_bb_rad(math.Atan2((%s).Number(), (%s).Number())))",
			w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "sqr":
		return fmt.Sprintf("value.Num(math.Sqrt((%s).Number()))", w.emitExprArg(args, 0, worldVar))
	case "abs":
		return fmt.Sprintf("value.Num(math.Abs((%s).Number()))", w.emitExprArg(args, 0, worldVar))
	case "floor":
		return fmt.Sprintf("value.Num(math.Floor((%s).Number()))", w.emitExprArg(args, 0, worldVar))
	case "ceil":
		return fmt.Sprintf("value.Num(math.Ceil((%s).Number()))", w.emitExprArg(args, 0, worldVar))
	case "int":
		return fmt.Sprintf("value.Num(math.Trunc((%s).Number()))", w.emitExprArg(args, 0, worldVar))
	case "min":
		return fmt.Sprintf("value.Num(math.Min((%s).Number(), (%s).Number()))",
			w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "max":
		return fmt.Sprintf("value.Num(math.Max((%s).Number(), (%s).Number()))",
			w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "rnd":
		return fmt.Sprintf("_bb_rnd((%s).Number())", w.emitExprArg(args, 0, worldVar))
	case "rand":
		two := "false"
		if len(args) >= 2 {
			two = "true"
		}
		return fmt.Sprintf("_bb_rand(int((%s).Number()), int((%s).Number()), %s)", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), two)
	case "millisecs":
		return "value.Num(float64(time.Since(_bb_start).Milliseconds()))"
	case "len":
		return fmt.Sprintf("value.Num(float64(len((%s).String())))", w.emitExprArg(args, 0, worldVar))
	case "upper":
		return fmt.Sprintf("value.Str(strings.ToUpper((%s).String()))", w.emitExprArg(args, 0, worldVar))
	case "lower":
		return fmt.Sprintf("value.Str(strings.ToLower((%s).String()))", w.emitExprArg(args, 0, worldVar))
	case "trim":
		return fmt.Sprintf("value.Str(strings.TrimSpace((%s).String()))", w.emitExprArg(args, 0, worldVar))
	case "left":
		return fmt.Sprintf("_bb_left((%s).String(), int((%s).Number()))", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "right":
		return fmt.Sprintf("_bb_right((%s).String(), int((%s).Number()))", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "mid":
		return fmt.Sprintf("_bb_mid((%s).String(), int((%s).Number()), int((%s).Number()))", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), w.emitExprArg(args, 2, worldVar))
	case "asc":
		return fmt.Sprintf("func() value.Value { s := (%s).String(); if s == \"\" { return value.Num(0) }; return value.Num(float64(s[0])) }()", w.emitExprArg(args, 0, worldVar))
	case "instr":
		return fmt.Sprintf("_bb_instr((%s).String(), (%s).String(), int((%s).Number()))", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), w.emitExprArg(args, 2, worldVar))
	case "replace":
		return fmt.Sprintf("_bb_replace((%s).String(), (%s).String(), (%s).String())", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), w.emitExprArg(args, 2, worldVar))
	case "string":
		return fmt.Sprintf("_bb_string(int((%s).Number()), (%s).String())", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "backbuffer":
		return "value.Num(0)"
	case "frontbuffer":
		return "value.Num(1)"
	case "setbuffer":
		return "value.Num(0)"
	case "arraysize":
		if len(args) < 2 {
			return fmt.Sprintf("_bb_arraysize(%s, 0)", w.emitExprArg(args, 0, worldVar))
		}
		return fmt.Sprintf("_bb_arraysize(%s, int((%s).Number()))", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "chr":
		return fmt.Sprintf("value.Str(string(rune(int((%s).Number()))))", w.emitExprArg(args, 0, worldVar))
	case "str":
		return fmt.Sprintf("value.Str((%s).String())", w.emitExprArg(args, 0, worldVar))
	case "hex":
		return fmt.Sprintf("_bb_hex(%s)", w.emitExprArg(args, 0, worldVar))
	case "copy":
		return fmt.Sprintf("(%s).DeepCopy()", w.emitExprArg(args, 0, worldVar))
	case "createmap":
		return "value.Map()"
	case "mapset":
		return fmt.Sprintf("_bb_map_set(%s, %s, %s)", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), w.emitExprArg(args, 2, worldVar))
	case "mapget":
		return fmt.Sprintf("_bb_map_get(%s, %s)", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "maphas":
		return fmt.Sprintf("_bb_map_has(%s, %s)", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "mapdelete":
		return fmt.Sprintf("_bb_map_delete(%s, %s)", w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "mapcount":
		return fmt.Sprintf("_bb_map_count(%s)", w.emitExprArg(args, 0, worldVar))
	case "createstatemachine":
		return "func() value.Value { id := _bb_mach_n; _bb_mach_n++; _bb_machs[id] = &_bbMach{fn: map[string]string{}}; return value.Num(float64(id)) }()"
	case "addstate":
		return fmt.Sprintf("func() value.Value { m := _bb_machs[int((%s).Number())]; if m == nil { return value.Num(0) }; name := strings.ToLower((%s).String()); m.fn[name] = strings.ToLower((%s).String()); if m.cur == \"\" { m.cur = name }; return value.Num(1) }()",
			w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar), w.emitExprArg(args, 2, worldVar))
	case "gostate":
		return fmt.Sprintf("func() value.Value { m := _bb_machs[int((%s).Number())]; if m == nil { return value.Num(0) }; m.cur = strings.ToLower((%s).String()); return value.Num(1) }()",
			w.emitExprArg(args, 0, worldVar), w.emitExprArg(args, 1, worldVar))
	case "statename":
		return fmt.Sprintf("func() value.Value { m := _bb_machs[int((%s).Number())]; if m == nil { return value.Str(\"\") }; return value.Str(m.cur) }()", w.emitExprArg(args, 0, worldVar))
	case "updatestate":
		return fmt.Sprintf("func() value.Value { m := _bb_machs[int((%s).Number())]; if m == nil { return value.Num(0) }; if fn, ok := _bb_callbacks[m.fn[m.cur]]; ok { return fn(%s) }; return value.Num(0) }()",
			w.emitExprArg(args, 0, worldVar), worldVar)
	}

	key := lex.IdentKey(name)
	if td, ok := w.types[key]; ok {
		return w.emitConstruct(td, args, worldVar)
	}

	argStrs := make([]string, len(args))
	for i, a := range args {
		argStrs[i] = w.emitExpr(a, worldVar)
	}
	if w.userFn[key] {
		if len(argStrs) == 0 {
			return fmt.Sprintf("%s(%s)", sanitizeFn(name), worldVar)
		}
		return fmt.Sprintf("%s(%s, %s)", sanitizeFn(name), worldVar, strings.Join(argStrs, ", "))
	}
	if call, ok := emitLangBuiltin(key, worldVar, argStrs); ok {
		return call
	}
	if w.isVar(name) {
		if len(argStrs) == 0 {
			return fmt.Sprintf("_bb_dispatch(%s, %s, %q)", worldVar, w.emitName(name), lower)
		}
		return fmt.Sprintf("_bb_dispatch(%s, %s, %q, %s)", worldVar, w.emitName(name), lower, strings.Join(argStrs, ", "))
	}
	if len(argStrs) == 0 {
		return fmt.Sprintf("_bb_call(%s, %q)", worldVar, lower)
	}
	return fmt.Sprintf("_bb_call(%s, %q, %s)", worldVar, lower, strings.Join(argStrs, ", "))
}

func (w *writer) isVar(name string) bool {
	id := sanitizeIdent(name)
	if w.inFunc && w.locals != nil && w.locals[id] {
		return true
	}
	for _, g := range w.globalNames {
		if g == id {
			return true
		}
	}
	return false
}

func loopNeedsLabel(stmts []ast.Stmt, kind string) bool {
	var walk func([]ast.Stmt, bool) bool
	walk = func(list []ast.Stmt, nested bool) bool {
		for _, s := range list {
			switch t := s.(type) {
			case *ast.ExitStmt:
				if t.Function {
					continue
				}
				if t.Loop == "" {
					if !nested {
						return true
					}
					continue
				}
				if t.Loop == kind {
					return true
				}
			case *ast.WhileStmt:
				if walk(t.Body, true) {
					return true
				}
			case *ast.ForStmt:
				if walk(t.Body, true) {
					return true
				}
			case *ast.RepeatStmt:
				if walk(t.Body, true) {
					return true
				}
			case *ast.IfStmt:
				if walk(t.Then, nested) || walk(t.Else, nested) {
					return true
				}
				for _, el := range t.ElseIf {
					if walk(el.Body, nested) {
						return true
					}
				}
			case *ast.SelectStmt:
				if walk(t.Default, nested) {
					return true
				}
				for _, c := range t.Cases {
					if walk(c.Body, nested) {
						return true
					}
				}
			case *ast.TryStmt:
				if walk(t.Body, nested) || walk(t.Catch, nested) {
					return true
				}
			}
		}
		return false
	}
	return walk(stmts, false)
}

func (w *writer) pushLoop(kind string) string {
	w.loopN++
	label := fmt.Sprintf("_bbL%d", w.loopN)
	w.loops = append(w.loops, loopFrame{kind: kind, label: label})
	return label
}

func (w *writer) popLoop() {
	if len(w.loops) > 0 {
		w.loops = w.loops[:len(w.loops)-1]
	}
}

func (w *writer) loopLabel(kind string) string {
	for i := len(w.loops) - 1; i >= 0; i-- {
		l := w.loops[i]
		if kind == "" || l.kind == kind {
			return l.label
		}
	}
	return ""
}

func (w *writer) emitConstruct(td *ast.TypeDecl, args []ast.Expr, worldVar string) string {
	var b strings.Builder
	b.WriteString("func() value.Value { _s := _bb_new_struct(")
	b.WriteString(strconv.Quote(strings.ToLower(td.Name)))
	b.WriteString("); ")
	for i, f := range td.Fields {
		if i >= len(args) || args[i] == nil {
			break
		}
		fmt.Fprintf(&b, "_s.SetField(%q, %s); ", strings.ToLower(strings.TrimRight(f.Name, "$#%")), w.emitExpr(args[i], worldVar))
	}
	b.WriteString("return _bb_track(_s) }()")
	return b.String()
}

func (w *writer) emitDot(recv ast.Expr, method string, args []ast.Expr, worldVar string) string {
	if id, ok := recv.(*ast.IdentExpr); ok {
		if call, ok := w.emitBuiltinDot(&ast.MethodStmt{Object: id.Name, Method: method, Args: args, Paren: true}, worldVar); ok {
			return call
		}
		key := lex.IdentKey(id.Name + "." + method)
		if w.userFn[key] {
			return w.emitCall(id.Name+"."+method, args, worldVar)
		}
	}
	recvStr := w.emitExpr(recv, worldVar)
	if len(args) == 0 {
		return fmt.Sprintf("_bb_dot(%s, %s, %q, true)", worldVar, recvStr, method)
	}
	argStrs := make([]string, len(args))
	for i, a := range args {
		argStrs[i] = w.emitExpr(a, worldVar)
	}
	return fmt.Sprintf("_bb_dot(%s, %s, %q, true, %s)", worldVar, recvStr, method, strings.Join(argStrs, ", "))
}

func (w *writer) emitMethodStmt(s *ast.MethodStmt, worldVar string) string {
	if len(s.Index) == 0 && len(s.Path) == 0 {
		if call, ok := w.emitBuiltinDot(s, worldVar); ok {
			return call
		}
	}
	key := lex.IdentKey(s.Object + "." + s.Method)
	if len(s.Index) == 0 && len(s.Path) == 0 && w.userFn[key] {
		return w.emitCall(s.Object+"."+s.Method, s.Args, worldVar)
	}
	var recv string
	if len(s.Index) > 0 {
		keys := make([]string, len(s.Index))
		for i, idx := range s.Index {
			keys[i] = w.emitExpr(idx, worldVar)
		}
		recv = fmt.Sprintf("_bb_index(%s, %s)", w.emitName(s.Object), strings.Join(keys, ", "))
	} else {
		recv = w.emitName(s.Object)
	}
	for _, f := range s.Path {
		recv = fmt.Sprintf("func() value.Value { if fld, ok := (%s).Field(%q); ok { return fld }; return value.Num(0) }()", recv, f)
	}
	paren := "false"
	if s.Paren {
		paren = "true"
	}
	if len(s.Args) == 0 {
		return fmt.Sprintf("_bb_dot(%s, %s, %q, %s)", worldVar, recv, s.Method, paren)
	}
	argStrs := make([]string, len(s.Args))
	for i, a := range s.Args {
		argStrs[i] = w.emitExpr(a, worldVar)
	}
	return fmt.Sprintf("_bb_dot(%s, %s, %q, %s, %s)", worldVar, recv, s.Method, paren, strings.Join(argStrs, ", "))
}

func (w *writer) emitBuiltinDot(s *ast.MethodStmt, worldVar string) (string, bool) {
	obj := lex.IdentKey(s.Object)
	method := lex.IdentKey(s.Method)
	switch obj {
	case "free":
		if method == "all" {
			return "_bb_erase_all()", true
		}
	case "string":
		switch method {
		case "interp":
			if len(s.Args) == 0 {
				return "_bb_sinterp()", true
			}
			args := make([]string, len(s.Args))
			for i, a := range s.Args {
				args[i] = w.emitExpr(a, worldVar)
			}
			return fmt.Sprintf("_bb_sinterp(%s)", strings.Join(args, ", ")), true
		case "format":
			spec := "\"\""
			if len(s.Args) > 1 {
				spec = fmt.Sprintf("strings.TrimPrefix((%s).String(), \"%%\")", w.emitExpr(s.Args[1], worldVar))
			}
			return fmt.Sprintf("value.Str(_bb_fmt(%s, %s))", w.emitExprArg(s.Args, 0, worldVar), spec), true
		}
	case "coroutine":
		switch method {
		case "start":
			return fmt.Sprintf("_bb_coro_start(%s, %s)", worldVar, w.emitExprArg(s.Args, 0, worldVar)), true
		case "wait":
			return fmt.Sprintf("func() value.Value { _bb_coro_wait((%s).Number()); return value.Num(0) }()", w.emitExprArg(s.Args, 0, worldVar)), true
		}
	}
	if plain, ok := stdlibPlain(obj, method); ok {
		return w.emitCall(plain, s.Args, worldVar), true
	}
	return "", false
}

// stdlibPlain maps Math.Sin, String.Upper, List.Count, and Input.KeyDown onto
// the same functions the interpreter runs.
func stdlibPlain(obj, method string) (string, bool) {
	switch obj {
	case "math":
		switch method {
		case "sqrt":
			return "sqr", true
		case "sign":
			return "sgn", true
		case "anglediff":
			return "angledelta", true
		case "dist2d":
			return "distance2d", true
		case "dist3d":
			return "distance3d", true
		case "sin", "cos", "tan", "asin", "acos", "atan", "atan2", "sqr", "abs",
			"int", "floor", "ceil", "float", "sgn", "min", "max", "rnd", "rand",
			"pow", "clamp", "lerp", "invlerp", "smoothstep", "easein", "easeout",
			"approach", "wrapangle", "angledelta", "approachangle",
			"distance2d", "distance3d", "pi":
			return method, true
		}
	case "string":
		if method == "length" {
			return "len", true
		}
		switch method {
		case "len", "left", "right", "mid", "chr", "asc", "str", "instr",
			"replace", "lower", "upper", "trim", "format":
			return method, true
		}
	case "list":
		switch method {
		case "add", "get", "set", "count", "remove":
			return "list" + method, true
		}
	case "map":
		switch method {
		case "set", "get", "has", "delete", "count":
			return "map" + method, true
		}
	case "array":
		if method == "size" {
			return "arraysize", true
		}
	case "input", "time", "entity", "file", "json", "sound", "net":
		return obj + "." + method, true
	}
	return "", false
}

func suffixNames(stmts []ast.Stmt) (ints, strs map[string]bool) {
	ints = map[string]bool{}
	strs = map[string]bool{}
	var note func(string)
	note = func(name string) {
		id := sanitizeIdent(name)
		switch {
		case strings.HasSuffix(name, "%"):
			ints[id] = true
		case strings.HasSuffix(name, "$"):
			strs[id] = true
		}
	}
	var walk func([]ast.Stmt)
	walk = func(list []ast.Stmt) {
		for _, s := range list {
			switch n := s.(type) {
			case *ast.AssignStmt:
				if len(n.Fields) == 0 && len(n.Index) == 0 {
					names := n.Names
					if len(names) == 0 {
						names = []string{n.Name}
					}
					for _, name := range names {
						note(name)
					}
				}
			case *ast.LocalStmt:
				for _, name := range n.Names {
					note(name)
				}
			case *ast.GlobalStmt:
				for _, name := range n.Names {
					note(name)
				}
			case *ast.ConstStmt:
				for _, name := range n.Names {
					note(name)
				}
			case *ast.ForStmt:
				note(n.Var)
				walk(n.Body)
			case *ast.FuncDecl:
				for _, p := range n.Params {
					note(p)
				}
				walk(n.Body)
			case *ast.TypeDecl:
				for _, m := range n.Methods {
					if m == nil {
						continue
					}
					for _, p := range m.Params {
						note(p)
					}
					walk(m.Body)
				}
			case *ast.MethodDecl:
				for _, p := range n.Params {
					note(p)
				}
				walk(n.Body)
			case *ast.NamespaceDecl:
				walk(n.Stmts)
			case *ast.IfStmt:
				walk(n.Then)
				for _, el := range n.ElseIf {
					walk(el.Body)
				}
				walk(n.Else)
			case *ast.WhileStmt:
				walk(n.Body)
			case *ast.RepeatStmt:
				walk(n.Body)
			case *ast.SelectStmt:
				for _, c := range n.Cases {
					walk(c.Body)
				}
				walk(n.Default)
			case *ast.TryStmt:
				walk(n.Body)
				walk(n.Catch)
			}
		}
	}
	walk(stmts)
	return ints, strs
}

func (w *writer) emitStore(name, expr string) string {
	sym := w.sym(name)
	id := sanitizeIdent(name)
	stored := expr
	if w.intNames[id] {
		stored = fmt.Sprintf("value.Num(float64(int((%s).Number())))", expr)
	} else if w.strNames[id] {
		stored = fmt.Sprintf("value.Str((%s).String())", expr)
	}
	if w.inFunc && w.shadow[id] {
		return fmt.Sprintf("{ %s = %s; %s_on = true }", sym, stored, sym)
	}
	return fmt.Sprintf("%s = %s", sym, stored)
}

func (w *writer) emitExprArg(args []ast.Expr, index int, worldVar string) string {
	if index < len(args) && args[index] != nil {
		return w.emitExpr(args[index], worldVar)
	}
	return "value.Num(0)"
}
